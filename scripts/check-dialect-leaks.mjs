#!/usr/bin/env node
/**
 * Which database it is, asked outside the adapter.
 *
 * The adapter exists so that nothing else has to know whether the server is MySQL or PostgreSQL: both answer the same
 * contract. Every `dialect === 'postgres'` in the API or the screens is a place that knows anyway, and a third database
 * would have to be found in each of them. So the number of such places is held where it is and may only go down,
 * until a difference is expressed as a capability (`packages/shared/src/capabilities.ts`) or moved into the adapter.
 *
 * A ratchet, like the file-size check:
 * - a file with more comparisons than `scripts/dialect-leaks-baseline.json` records fails, and so does a new file
 *   with any: ask for the capability (or move the work into the adapter's `ddl` / `export`) instead;
 * - a file with fewer fails until the baseline says so, so the number only goes down. `--update-baseline` does that
 *   part; it never adds a file or raises a number.
 * Tests, the adapter's own dialect directories and its fakes are not counted. The language strings and the Docker
 * discovery (it names engines, it does not branch on a capability) are exempt, with why.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const BASELINE_FILE = 'scripts/dialect-leaks-baseline.json'
const SCOPES = ['apps/api/src', 'apps/web/src', 'packages/adapter/src', 'packages/shared/src']
const SKIP_DIRS = new Set(['node_modules', 'dist', '.git', 'test', 'testing', 'mysql', 'postgres'])
const EXTENSIONS = ['.ts', '.tsx']
/** [path pattern, why]. */
const EXEMPT = [
  [/\.test\.tsx?$/, 'a test'],
  [/(^|\/)routeTree\.gen\.ts$/, 'generated by the router'],
  [/^apps\/web\/src\/config\/locales\//, 'language strings'],
  [/^apps\/api\/src\/lib\/docker-discovery\.ts$/, 'names the engine of a container; no capability is branched on'],
]
/** `dialect === 'postgres'`, `session.dialect !== 'mysql'`, `adapter.dialect === "postgres"`. */
const COMPARISON = /\bdialect\s*[!=]==?\s*['"](?:mysql|postgres)['"]/g

/** How many comparisons a source text makes. */
export function countLeaks(text) {
  return (text.match(COMPARISON) ?? []).length
}

/**
 * What is wrong, given each file's count and the baseline ({ path: count }).
 * @param {{ path: string, leaks: number }[]} files
 * @param {Record<string, number>} baseline
 */
export function evaluate(files, baseline) {
  const problems = []
  const seen = new Set()
  for (const { path, leaks } of files) {
    seen.add(path)
    const known = baseline[path] ?? 0
    if (leaks > known) {
      problems.push(
        known === 0
          ? `${path}: ${leaks} comparison(s) of the dialect. Use a capability (packages/shared/src/capabilities.ts) or move the work into the adapter`
          : `${path}: ${leaks} comparisons of the dialect, was ${known}. Use a capability or move the work into the adapter`
      )
    } else if (leaks < known) {
      problems.push(
        `${path}: down to ${leaks} (was ${known}); lower the baseline (bun run check:dialect-leaks -- --update-baseline)`
      )
    }
  }
  for (const path of Object.keys(baseline)) {
    if (!seen.has(path)) problems.push(`${path}: in ${BASELINE_FILE} but gone; remove it (--update-baseline)`)
  }
  return problems
}

/** The baseline with every number that fell lowered and every file that reached 0 (or is gone) removed. */
export function lowered(files, baseline) {
  const now = new Map(files.map((f) => [f.path, f.leaks]))
  const out = {}
  for (const [path, known] of Object.entries(baseline)) {
    const leaks = Math.min(known, now.get(path) ?? 0)
    if (leaks > 0) out[path] = leaks
  }
  return out
}

function selfTest() {
  const assert = (cond, what) => {
    if (!cond) throw new Error(`self-test failed: ${what}`)
  }
  assert(countLeaks("if (dialect === 'postgres') a(); b(adapter.dialect !== 'mysql')") === 2, 'two comparisons')
  assert(countLeaks("const d: Dialect = 'postgres'; dialect: 'mysql'") === 0, 'a value is not a comparison')
  assert(countLeaks('x ? dialect === "mysql" : 0') === 1, 'double quotes')
  const base = { 'a.ts': 3 }
  assert(evaluate([{ path: 'a.ts', leaks: 3 }], base).length === 0, 'unchanged passes')
  assert(evaluate([{ path: 'a.ts', leaks: 4 }], base).length === 1, 'growth fails')
  assert(evaluate([{ path: 'a.ts', leaks: 2 }], base).length === 1, 'a fall must be recorded')
  assert(
    evaluate(
      [
        { path: 'a.ts', leaks: 3 },
        { path: 'b.ts', leaks: 1 },
      ],
      base
    ).length === 1,
    'a new file with one fails'
  )
  assert(
    evaluate(
      [
        { path: 'a.ts', leaks: 3 },
        { path: 'b.ts', leaks: 0 },
      ],
      base
    ).length === 0,
    'a new file with none passes'
  )
  assert(evaluate([], base).length === 1, 'a gone file must be removed')
  const next = lowered(
    [
      { path: 'a.ts', leaks: 1 },
      { path: 'b.ts', leaks: 0 },
      { path: 'n.ts', leaks: 9 },
    ],
    { 'a.ts': 3, 'b.ts': 2, 'gone.ts': 1 }
  )
  assert(JSON.stringify(next) === JSON.stringify({ 'a.ts': 1 }), 'lowering lowers, drops zero and gone, adds nothing')
  console.log('✓ dialect-leaks self-test passed')
}

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || (e.isDirectory() && SKIP_DIRS.has(e.name))) continue
    const full = join(dir, e.name)
    if (e.isDirectory()) walk(full, out)
    else if (EXTENSIONS.some((x) => e.name.endsWith(x))) out.push(full)
  }
  return out
}

function measure(root) {
  const files = []
  for (const scope of SCOPES) {
    for (const f of walk(join(root, scope))) {
      const path = relative(root, f)
      if (EXEMPT.some(([re]) => re.test(path))) continue
      files.push({ path, leaks: countLeaks(readFileSync(f, 'utf8')) })
    }
  }
  return files
}

function main() {
  const args = process.argv.slice(2)
  if (args.includes('--self-test')) return selfTest()
  const root = process.cwd()
  const files = measure(root)
  const total = files.reduce((n, f) => n + f.leaks, 0)
  if (args.includes('--update-baseline')) {
    const old = JSON.parse(readFileSync(join(root, BASELINE_FILE), 'utf8')).files
    const next = lowered(files, old)
    writeFileSync(join(root, BASELINE_FILE), `${JSON.stringify({ files: next }, null, 2)}\n`)
    console.log(`✓ ${BASELINE_FILE} updated (${Object.keys(next).length} files; nothing added, nothing raised)`)
    return
  }
  if (args.includes('--write-initial')) {
    const initial = Object.fromEntries(
      files
        .filter((f) => f.leaks > 0)
        .sort((a, b) => a.path.localeCompare(b.path))
        .map((f) => [f.path, f.leaks])
    )
    writeFileSync(join(root, BASELINE_FILE), `${JSON.stringify({ files: initial }, null, 2)}\n`)
    console.log(`✓ ${BASELINE_FILE} written: ${Object.keys(initial).length} files, ${total} comparisons`)
    return
  }
  const baseline = JSON.parse(readFileSync(join(root, BASELINE_FILE), 'utf8')).files
  const problems = evaluate(files, baseline)
  for (const p of problems) console.error(`✗ ${p}`)
  if (problems.length > 0) {
    console.error(
      `✗ dialect-leaks check FAILED (${problems.length}): the number of places that ask which database it is may only go down`
    )
    process.exit(1)
  }
  console.log(`✓ dialect-leaks check passed (${total} comparisons in ${Object.keys(baseline).length} files)`)
}

main()
