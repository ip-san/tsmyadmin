#!/usr/bin/env node
/**
 * Files too long to read.
 *
 * A file past LIMIT lines is more than a person holds in their head: they scroll, lose the top, and stop trusting
 * what they remember of it. Two files of this repository reached 3,000 and 5,000 lines before anyone split them.
 *
 * The check is a ratchet, so it can start where the repository is:
 * - a file past LIMIT that is not in `scripts/file-size-baseline.json` fails (a new one, or one that grew past it);
 * - a file in the baseline fails if it grew past the number recorded there;
 * - a file in the baseline that shrank (or went under LIMIT, or is gone) fails until the baseline says so, so the
 *   number only goes down. `--update-baseline` does that part; it never adds a file or raises a number, because
 *   that is the decision this check exists to make a person take, in a diff someone reads.
 * Generated code and the string tables are exempt (EXEMPT, with why).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { pathToFileURL } from 'node:url'

export const LIMIT = 800
/** Not counted as a failure, but named at the end: where the next split would help. */
const SOFT_LIMIT = 500

const SKIP_DIRS = new Set(['node_modules', 'dist', '.git', '.claude', 'test-results', 'playwright-report', 'coverage'])
const EXTENSIONS = ['.ts', '.tsx', '.mjs']
/** [path pattern, why]. */
const EXEMPT = [
  [/(^|\/)routeTree\.gen\.ts$/, 'generated by the router'],
  [
    /^apps\/web\/src\/config\/locales\/[a-z]+\.ts$/,
    'a language is one string table read at load; splitting it by screen is a redesign (docs/dev-environment.md)',
  ],
]
const BASELINE_FILE = 'scripts/file-size-baseline.json'

/**
 * What is wrong, given each file's line count and the baseline ({ path: { lines, why } }).
 * @param {{ path: string, lines: number }[]} files
 * @param {Record<string, { lines: number, why: string }>} baseline
 * @returns {string[]}
 */
export function evaluate(files, baseline, limit = LIMIT, exempt = EXEMPT) {
  const problems = []
  const seen = new Set()
  for (const { path, lines } of files) {
    seen.add(path)
    if (exempt.some(([re]) => re.test(path))) continue
    const known = baseline[path]
    if (lines > limit) {
      if (!known) {
        problems.push(
          `${path}: ${lines} lines, past ${limit}. Split it by what it holds; if it truly cannot be split, add it to ${BASELINE_FILE} with the reason`
        )
      } else if (lines > known.lines) {
        problems.push(
          `${path}: grew from ${known.lines} to ${lines} lines (it is already past ${limit}); split it instead`
        )
      } else if (lines < known.lines) {
        problems.push(
          `${path}: shrank to ${lines} lines; lower its baseline from ${known.lines} (bun run check:file-size -- --update-baseline)`
        )
      }
    } else if (known) {
      problems.push(
        `${path}: ${lines} lines, under ${limit} now; remove it from ${BASELINE_FILE} (bun run check:file-size -- --update-baseline)`
      )
    }
  }
  for (const path of Object.keys(baseline)) {
    if (!seen.has(path))
      problems.push(`${path}: in ${BASELINE_FILE} but gone; remove it (bun run check:file-size -- --update-baseline)`)
  }
  return problems
}

/** The baseline with every number that fell lowered and every file that is under the limit or gone removed. */
export function lowered(files, baseline, limit = LIMIT) {
  const lines = new Map(files.map((f) => [f.path, f.lines]))
  const out = {}
  for (const [path, known] of Object.entries(baseline)) {
    const now = lines.get(path)
    if (now === undefined || now <= limit) continue
    out[path] = { ...known, lines: Math.min(known.lines, now) }
  }
  return out
}

const SELF_TEST = [
  { name: 'a short file', files: [{ path: 'a.ts', lines: 120 }], baseline: {}, expect: 0 },
  { name: 'a new file past the limit', files: [{ path: 'a.ts', lines: 801 }], baseline: {}, expect: 1 },
  { name: 'exactly at the limit', files: [{ path: 'a.ts', lines: 800 }], baseline: {}, expect: 0 },
  {
    name: 'a baselined file that stayed as it was',
    files: [{ path: 'a.ts', lines: 1200 }],
    baseline: { 'a.ts': { lines: 1200, why: 'x' } },
    expect: 0,
  },
  {
    name: 'a baselined file that grew',
    files: [{ path: 'a.ts', lines: 1201 }],
    baseline: { 'a.ts': { lines: 1200, why: 'x' } },
    expect: 1,
  },
  {
    name: 'a baselined file that shrank but is still long',
    files: [{ path: 'a.ts', lines: 1000 }],
    baseline: { 'a.ts': { lines: 1200, why: 'x' } },
    expect: 1,
  },
  {
    name: 'a baselined file now under the limit',
    files: [{ path: 'a.ts', lines: 500 }],
    baseline: { 'a.ts': { lines: 1200, why: 'x' } },
    expect: 1,
  },
  { name: 'a baselined file that is gone', files: [], baseline: { 'a.ts': { lines: 1200, why: 'x' } }, expect: 1 },
  {
    name: 'a generated file',
    files: [{ path: 'apps/web/src/routeTree.gen.ts', lines: 5000 }],
    baseline: {},
    expect: 0,
  },
  {
    name: 'a string table',
    files: [{ path: 'apps/web/src/config/locales/ja.ts', lines: 2600 }],
    baseline: {},
    expect: 0,
  },
  {
    name: 'a file named like a table but elsewhere',
    files: [{ path: 'apps/web/src/other/locales/ja.ts', lines: 2600 }],
    baseline: {},
    expect: 1,
  },
]

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || SKIP_DIRS.has(e.name)) continue
    const full = join(dir, e.name)
    if (e.isDirectory()) walk(full, out)
    else if (EXTENSIONS.some((x) => e.name.endsWith(x))) out.push(full)
  }
  return out
}

const countLines = (text) => text.split('\n').length - (text.endsWith('\n') ? 1 : 0)

function main() {
  const args = process.argv.slice(2)
  if (args.includes('--self-test')) {
    const failed = SELF_TEST.filter((c) => evaluate(c.files, c.baseline).length !== c.expect)
    for (const c of failed) console.error(`  - ${c.name}: got ${JSON.stringify(evaluate(c.files, c.baseline))}`)
    const lowers = lowered(
      [
        { path: 'a.ts', lines: 1000 },
        { path: 'b.ts', lines: 300 },
        { path: 'c.ts', lines: 2000 },
      ],
      {
        'a.ts': { lines: 1200, why: 'x' },
        'b.ts': { lines: 900, why: 'y' },
        'gone.ts': { lines: 900, why: 'z' },
        'c.ts': { lines: 1500, why: 'w' },
      }
    )
    if (
      JSON.stringify(Object.entries(lowers).map(([p, v]) => [p, v.lines])) !==
      JSON.stringify([
        ['a.ts', 1000],
        ['c.ts', 1500],
      ])
    ) {
      failed.push({ name: '--update-baseline lowers, removes, and never raises' })
    }
    if (failed.length) {
      console.error('✗ file-size self-test FAILED')
      process.exit(1)
    }
    console.log(`✓ file-size self-test passed (${SELF_TEST.length + 1} cases)`)
    return
  }
  const root = process.cwd()
  const files = walk(root).map((f) => ({ path: relative(root, f), lines: countLines(readFileSync(f, 'utf8')) }))
  const baseline = JSON.parse(readFileSync(join(root, BASELINE_FILE), 'utf8')).files
  if (args.includes('--update-baseline')) {
    const next = lowered(files, baseline)
    writeFileSync(join(root, BASELINE_FILE), `${JSON.stringify({ limit: LIMIT, files: next }, null, 2)}\n`)
    console.log(`✓ ${BASELINE_FILE} updated (${Object.keys(next).length} files; nothing added, nothing raised)`)
    return
  }
  const problems = evaluate(files, baseline)
  for (const p of problems) console.error(`✗ ${p}`)
  if (problems.length) {
    console.error(
      `✗ file-size check FAILED (${problems.length}). A file this long is hard to read: split it by what it holds.`
    )
    process.exit(1)
  }
  const soft = files.filter((f) => f.lines > SOFT_LIMIT && f.lines <= LIMIT && !EXEMPT.some(([re]) => re.test(f.path)))
  console.log(
    `✓ file-size check passed (${files.length} files; ${Object.keys(baseline).length} past ${LIMIT} on the baseline; ${soft.length} between ${SOFT_LIMIT} and ${LIMIT})`
  )
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
